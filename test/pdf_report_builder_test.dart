/// Parses raw PDF bytes generated by `package:pdf`, returning the page count
/// and the extracted literal text strings per page in order.
class _ParsedPdf {
  const _ParsedPdf({required this.pageCount, required this.pageTexts});

  final int pageCount;
  final List<String> pageTexts;

  String get fullText => pageTexts.join('\n---PAGE---\n');
}

_ParsedPdf _inspectPdf(Uint8List bytes) {
  final raw = latin1.decode(bytes, allowInvalid: true);

  // Build map of object number -> raw object body.
  final objHeaderRegex = RegExp(r'(\d+)\s+0\s+obj\b');
  final objMatches = objHeaderRegex.allMatches(raw).toList(growable: false);
  final objectRanges = <int, ({int start, int end})>{};
  for (var i = 0; i < objMatches.length; i++) {
    final objNum = int.parse(objMatches[i].group(1)!);
    final start = objMatches[i].end;
    final end = raw.indexOf('endobj', start);
    if (end > start) {
      objectRanges[objNum] = (start: start, end: end);
    }
  }

  // Locate individual page objects (`/Type /Page` but not `/Type /Pages`).
  final pageTypeRegex = RegExp(r'/Type\s*/Page(?![A-Za-z])');
  final pageObjNums = <int>[];
  for (final entry in objectRanges.entries) {
    final body = raw.substring(entry.value.start, entry.value.end);
    if (pageTypeRegex.hasMatch(body)) {
      pageObjNums.add(entry.key);
    }
  }

  final pageTexts = <String>[];
  for (final pageObjNum in pageObjNums) {
    final range = objectRanges[pageObjNum]!;
    final body = raw.substring(range.start, range.end);

    // Extract /Contents reference(s): `/Contents 5 0 R` or `/Contents [5 0 R 6 0 R]`.
    final contentRefs = <int>[];
    final singleRef = RegExp(r'/Contents\s+(\d+)\s+0\s+R').firstMatch(body);
    if (singleRef != null) {
      contentRefs.add(int.parse(singleRef.group(1)!));
    } else {
      final arrayMatch = RegExp(r'/Contents\s*\[([^\]]+)\]').firstMatch(body);
      if (arrayMatch != null) {
        for (final ref in RegExp(r'(\d+)\s+0\s+R').allMatches(arrayMatch.group(1)!)) {
          contentRefs.add(int.parse(ref.group(1)!));
        }
      }
    }

    final pageBuffer = StringBuffer();
    for (final contentRef in contentRefs) {
      final cRange = objectRanges[contentRef];
      if (cRange == null) continue;
      final contentHeader = raw.substring(cRange.start, cRange.end);
      final streamIdx = raw.indexOf('stream', cRange.start);
      final endStreamIdx = raw.indexOf('endstream', cRange.start);
      if (streamIdx < 0 || endStreamIdx <= streamIdx || endStreamIdx > cRange.end) {
        continue;
      }

      var dataStart = streamIdx + 'stream'.length;
      if (dataStart < bytes.length && bytes[dataStart] == 0x0D) dataStart++;
      if (dataStart < bytes.length && bytes[dataStart] == 0x0A) dataStart++;

      var dataEnd = endStreamIdx;
      while (dataEnd > dataStart &&
          (bytes[dataEnd - 1] == 0x0A || bytes[dataEnd - 1] == 0x0D)) {
        dataEnd--;
      }

      final streamSlice = bytes.sublist(dataStart, dataEnd);
      String decodedStream;
      if (contentHeader.contains('/FlateDecode')) {
        decodedStream = latin1.decode(
          zlib.decode(streamSlice),
          allowInvalid: true,
        );
      } else {
        decodedStream = latin1.decode(streamSlice, allowInvalid: true);
      }

      pageBuffer.writeln(_extractPdfStrings(decodedStream));
    }
    pageTexts.add(pageBuffer.toString());
  }

  return _ParsedPdf(pageCount: pageObjNums.length, pageTexts: pageTexts);
}

/// Extracts literal `(text)` operands inside PDF content stream `TJ`/`Tj` ops.
String _extractPdfStrings(String contentStream) {
  final out = StringBuffer();
  var i = 0;
  while (i < contentStream.length) {
    if (contentStream.codeUnitAt(i) == 0x28 /* '(' */) {
      i++;
      var depth = 1;
      final token = StringBuffer();
      while (i < contentStream.length && depth > 0) {
        final c = contentStream.codeUnitAt(i);
        if (c == 0x5C /* '\\' */ && i + 1 < contentStream.length) {
          i++;
          final escaped = contentStream.codeUnitAt(i);
          switch (escaped) {
            case 0x6E: // n
              token.write('\n');
            case 0x72: // r
              token.write('\r');
            case 0x74: // t
              token.write('\t');
            default:
              token.writeCharCode(escaped);
          }
          i++;
          continue;
        }
        if (c == 0x28) {
          depth++;
          token.writeCharCode(c);
        } else if (c == 0x29) {
          depth--;
          if (depth > 0) token.writeCharCode(c);
        } else {
          token.writeCharCode(c);
        }
        i++;
      }
      if (token.isNotEmpty) {
        if (out.isNotEmpty) out.write(' ');
        out.write(token.toString());
      }
    } else {
      i++;
    }
  }
  return out.toString();
}

ScanRecord _makeRecord({
  required int sessionId,
  required int index,
  required Set<ApdItem> requiredApd,
  required ApdStatus Function(ApdItem item, int index) statusFor,
}) {
  final results = <ApdItem, ApdCheckResult>{
    for (final item in requiredApd)
      item: ApdCheckResult(
        item: item,
        status: statusFor(item, index),
        confidence: statusFor(item, index) == ApdStatus.detected ? 0.92 : 0.45,
      ),
  };
  return ScanRecord(
    id: index,
    sessionId: sessionId,
    nisn: '008100${index.toString().padLeft(4, '0')}',
    attendanceNo: index.toString().padLeft(2, '0'),
    studentName: 'Siswa Bengkel Ke-$index',
    apdResults: results,
    scannedAt: DateTime(2026, 11, 24, 8, 10 + (index % 40)),
  );
}

